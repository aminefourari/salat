# Regenerates src/server/cities.data.ts from GeoNames cities5000.txt:
#   python3 -I scripts/cities.py cities5000.txt src/server/cities.data.ts
import json, re, sys
src, dst = sys.argv[1], sys.argv[2]
raw = []
for line in open(src, encoding='utf-8'):
    f = line.rstrip('\n').split('\t')
    if f[7] == 'PPLX':  # sections of a city: show the city itself
        continue
    assert '|' not in f[1]
    raw.append((f[1], float(f[4]), float(f[5]), f[8]))
# Numbered districts ("Paris 04 Hôtel-de-Ville", "Lyon 03") are tagged PPL; drop them when the city exists.
names = {(n, cc) for n, _, _, cc in raw}
district = re.compile(r'^(.+?) \d{2}\b')
dropped = [n for n, _, _, cc in raw if (m := district.match(n)) and (m.group(1), cc) in names]
rows = [f"{n}|{lat:.2f}|{lon:.2f}|{cc}" for n, lat, lon, cc in raw if n not in dropped]
body = '\n'.join(rows)
with open(dst, 'w', encoding='utf-8') as o:
    o.write('// Generated by scripts/cities.py from GeoNames cities5000 (CC BY 4.0, https://www.geonames.org). name|lat|lon|country per line.\n')
    o.write('export default ' + json.dumps(body, ensure_ascii=False) + '\n')
print(len(rows), len(body), 'dropped:', len(dropped), dropped[:50])
